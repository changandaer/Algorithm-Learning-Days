losses = [1.0, 1.1]

# 我的拆题
# 输入：容器为列表，元素为浮点数
# 输出：列表中元素第一次变大的位置
# 中文伪代码：
# 遍历输入列表，对比第 i 个元素和第 i+1 个元素的大小
# 如果 第 i+1 个元素 大于 第 i 个元素，记录位置并跳出for循环结束后续查找
# 如果 第 i+1 个元素 小于 第 i 个元素，继续后续对比，直至最后一个元素

# 最小样例的手算过程：
# 必须记住的状态：第一次变大的位置，是否存在反弹
# 重复动作与控制结构：
# 普通测试、边界测试、反例：


# 从这里开始实现。完成后替换 losses 测试无反弹和立即反弹。

is_bound = False
for index in range(len(losses)-1):
    if losses[index+1] > losses[index]:
        # print(f'训练损失第一次比前一轮升高的位置是第{index+2}次损失')
        is_bound = True
        break
    else:
        pass
if is_bound:
    print(f'训练损失第一次比前一轮升高的位置是第{index+2}次损失')
else:
    print(f"损失没有反弹")